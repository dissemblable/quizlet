/**
 * Fuseaux IANA proposés dans les paramètres, triés. `Intl.supportedValuesOf('timeZone')` si
 * disponible (dans un try/catch : absent ou incomplet sur Hermes), sinon une liste statique.
 * `current` (fuseau déjà enregistré, éventuellement absent de la liste) est toujours inclus.
 * Pas de doublon.
 */
export function listTimeZones(current?: string | null): string[] {
  let zones: readonly string[] = []
  try {
    zones = Intl.supportedValuesOf('timeZone')
  } catch {
    // Hermes : API absente.
  }
  if (zones.length === 0) zones = FALLBACK_TIME_ZONES
  const all = new Set(zones)
  if (current) all.add(current)
  return Array.from(all).sort()
}
